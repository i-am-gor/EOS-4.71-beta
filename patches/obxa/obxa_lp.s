| OB-Xa CEM3320 lowpass family for EOS 4.70 (replaces 2/4/6 Pole Low-pass methods).
| Assembled for MCF5206e, linked at 0x65E18 into the region previously holding
| FUN_00065E18 + the LP2/LP4/LP6 type/getName/computeFrames/packQ methods (0x65E18-0x660BF).
|
| Behaviour kept from stock: FUN_0010D3B0(blk, mode, 0x40); zero words 1,5 = neutral;
| gain word 9 and return values computed exactly as stock (gain tables 0x6871C / 0x6879C).
| Changed: pole words 0,4,8 come from 32-step tables (index q>>2):
|   2-pole: w0 = SVF                  4-pole: w0 = LADA, w4 = LADB
|   6-pole: w0 = LADA, w4 = LADB, w8 = SVF, index capped at LP6_CAP
| LADB (heavily damped pair, nearly constant) uses 16 steps, index (q>>2)>>1.
| Tables are generated by tools/obxa.py into tables.inc.

        .equ    NEUTRAL,  0xFFCFFFCF
        .equ    GAINBASE, 0x10004D7C
        .equ    GOFF,     0x0006871C
        .equ    RGAIN,    0x0006879C
        .equ    SETMODE,  0x0010D3B0
        .equ    NAME2,    0x00068CCC
        .equ    NAME4,    0x00068CDC
        .equ    NAME6,    0x00068CEC
        .equ    LADB16,   0x0006875C        | 16-step ladder pair B, in the old RES16 slot

        .text
        .globl  _start
_start:

| ---- type / getName (same values as stock) ----
lp2_type:   moveq   #1,%d0
            rts
lp2_name:   move.l  #NAME2,%d0
            rts
lp4_type:   moveq   #0,%d0
            rts
lp4_name:   move.l  #NAME4,%d0
            rts
lp6_type:   moveq   #2,%d0
            rts
lp6_name:   move.l  #NAME6,%d0
            rts

| ---- thunks: P (pole count) in d0 ----
lp2_cf:     moveq   #2,%d0
            bra.s   cf
lp4_cf:     moveq   #4,%d0
            bra.s   cf
lp6_cf:     moveq   #6,%d0
            bra.s   cf
lp2_pq:     moveq   #2,%d0
            bra.w   pq
lp4_pq:     moveq   #4,%d0
            bra.w   pq
lp6_pq:     moveq   #6,%d0
            bra.w   pq

| ---- words: in d7 = P, d1 = q ; out d0 = w0, d1 = w4, d5 = w8 ; clobbers a0, a1 ----
words:      lsr.l   #2,%d1
            andi.l  #31,%d1
            cmpi.l  #6,%d7
            bne.s   1f
            cmpi.l  #LP6_CAP,%d1
            ble.s   1f
            moveq   #LP6_CAP,%d1
1:          lea     LADB16,%a0
            move.l  %d1,%d0
            lsr.l   #1,%d0
            lea     0(%a0,%d0.l*4),%a0      | a0 -> LADB16[idx>>1]
            lea     tables,%a1
            lea     0(%a1,%d1.l*4),%a1      | a1 -> SVF[idx]
            move.l  #NEUTRAL,%d1
            move.l  %d1,%d5
            move.l  (%a1),%d0               | SVF
            cmpi.l  #2,%d7
            beq.s   9f                      | 2-pole: SVF, N, N
            cmpi.l  #4,%d7
            beq.s   4f
            move.l  %d0,%d5                 | 6-pole: w8 = SVF
4:          move.l  128(%a1),%d0            | LADA
            move.l  (%a0),%d1               | LADB
9:          rts

| ---- computeFrames(this, blk, mode, q) ----
cf:         lea     -16(%sp),%sp
            movem.l %d5-%d7/%a5,(%sp)       | args: blk 0x18, mode 0x1C, q 0x20
            move.l  %d0,%d7
            movea.l 0x18(%sp),%a5
            moveq   #0,%d0
            move.b  0x1F(%sp),%d0
            pea     0x40.w
            move.l  %d0,-(%sp)
            move.l  %a5,-(%sp)
            jsr     SETMODE
            lea     12(%sp),%sp
            move.l  0x20(%sp),%d1
            bsr.s   words
            move.l  %d0,(%a5)
            move.l  %d1,0x10(%a5)
            move.l  %d5,0x20(%a5)
            move.l  #NEUTRAL,%d0
            move.l  %d0,4(%a5)
            move.l  %d0,0x14(%a5)
            move.l  0x20(%sp),%d1           | gain index as stock
            cmpi.l  #6,%d7
            bne.s   1f
            move.l  %d1,%d0
            asr.l   #2,%d0
            sub.l   %d0,%d1                 | q - q>>2
1:          asr.l   #3,%d1
            andi.l  #15,%d1
            lea     GOFF,%a1
            move.l  0(%a1,%d1.l*4),%d6
            lea     RGAIN,%a1
            move.l  0(%a1,%d1.l*4),%d0
            move.l  GAINBASE,%d1
            cmpi.l  #4,%d7
            beq.s   4f
            bgt.s   6f
            lsr.l   #1,%d6                  | 2-pole
            sub.l   %d6,%d1
            asr.l   #1,%d0
            bra.s   9f
4:          sub.l   %d6,%d1                 | 4-pole
            bra.s   9f
6:          sub.l   %d6,%d1                 | 6-pole
            lsr.l   #1,%d6
            sub.l   %d6,%d1
            add.l   %d0,%d0
9:
        .if DRIVE
            movea.l 0x24(%sp),%a0           | filter-parameter struct (5th arg)
            jsr     drive_apply             | v3c: d1 += Drive (struct+6) << 14
        .endif
            move.l  %d1,0x24(%a5)
            movem.l (%sp),%d5-%d7/%a5
            lea     16(%sp),%sp
            rts

| ---- packQ(this, blk, q) ----
pq:         move.l  %d5,-(%sp)
            move.l  %d7,-(%sp)              | args: blk 0x10, q byte 0x17
            move.l  %d0,%d7
            moveq   #0,%d1
            move.b  0x17(%sp),%d1
            bsr.w   words
            movea.l 0x10(%sp),%a0
            move.l  %d0,(%a0)
            cmpi.l  #2,%d7
            beq.s   1f
            move.l  %d1,0x10(%a0)
            cmpi.l  #4,%d7
            beq.s   1f
            move.l  %d5,0x20(%a0)
1:          moveq   #0,%d0
            move.b  0x17(%sp),%d0
            moveq   #-10,%d1
            cmpi.l  #2,%d7
            beq.s   2f
            moveq   #-20,%d1
            cmpi.l  #4,%d7
            beq.s   2f
            moveq   #-40,%d1
            move.l  %d0,%d5
            lsr.l   #2,%d5
            sub.l   %d5,%d0                 | q' = q - q>>2
2:          muls.l  %d1,%d0
            asr.l   #7,%d0
            move.l  (%sp)+,%d7
            move.l  (%sp)+,%d5
            rts

            .balign 4
tables:     .include "tables.inc"           | SVF[32], LADA[32]  (LADB16 lives at 0x6875C)
end_of_patch:

| ===================== v3c extension, linked at 0x68BF0 =====================
| Occupies the four dormant (unreferenced) filter method tables 0x68BF0-0x68C9F (176 bytes).
| Drive = filter parameter index 2, stored at struct+6 like the morph filters' extra parameters.
        .equ    STRCPY,   0x001A6C4C
        .equ    SPRINTF,  0x001A6EA0
        .equ    FMT_D,    0x00068CB0        | "%d"
        .equ    LP_FMT,   0x00065D24        | stock LP formatParam (Frequency / Resonance)

            .section .ext,"ax"
| numParams: Frequency, Resonance, Drive
lp_nparams: moveq   #3,%d0
            rts

| formatParam(this, idx, value, labelbuf, valuebuf): idx 2 -> "Drive" / "%d", else stock
lp_fmt:     move.l  8(%sp),%d0
            cmpi.l  #2,%d0
            beq.s   1f
            jmp     LP_FMT
1:          pea     drive_str
            move.l  0x14(%sp),-(%sp)        | labelbuf (0x10 + 4 pushed)
            jsr     STRCPY
            addq.l  #8,%sp
            move.l  0xc(%sp),-(%sp)         | value
            pea     FMT_D
            move.l  0x1c(%sp),-(%sp)        | valuebuf (0x14 + 8 pushed)
            jsr     SPRINTF
            lea     12(%sp),%sp
            rts

| drive_apply: in a0 = struct (may be 0), d1 = gain word; out d1 += min(drive,127) << 14.
| Preserves d0 (computeFrames return value); clobbers d6.
drive_apply:
            move.l  %a0,%d6
            beq.s   9f
            moveq   #0,%d6
            move.b  6(%a0),%d6
            cmpi.l  #127,%d6
            bls.s   1f
            moveq   #127,%d6
1:          lsl.l   #8,%d6
            lsl.l   #6,%d6
            add.l   %d6,%d1
9:          rts

drive_str:  .asciz  "Drive"
            .balign 2
end_of_ext:
