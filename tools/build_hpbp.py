#!/usr/bin/env python3
"""Build the OB-Xa high-pass / band-pass / contrary band-pass patch on top of an EOS 4.70 image (Sync6+Transwave).

usage: build_hpbp.py BASE.bin OUT.bin [NAME]
Assembles patches/hpbp/hpbp.s: sections .hp2/.hp4/.bp2/.bp4 into the stock computeFrames+packQ bodies
of 2nd/4th Order High-pass and Band-pass, .hdr2 into the image header padding after the Transwave code.
Repoints vtable slots +0x14 (computeFrames) and +0x18 (packQ); names, types, formatParam, chip mode,
zero words, gain word and return values stay stock.
"""
import os, struct, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import eos_lz   # noqa: E402
import hpbp     # noqa: E402

ROOT = os.path.dirname(HERE)
PDIR = os.path.join(ROOT, 'patches', 'hpbp')
BASE = 0x20000
BIN = '/opt/homebrew/bin/'
NAME = b'EOS 4.70 Sync8+TW+HPBP6'
# section -> (start, end) : exact stock cf+pq extents (functions.tsv)
SECTIONS = {'.hp2': (0x660CC, 0x66178), '.hp4': (0x66278, 0x6632C), '.bp2': (0x668A8, 0x66980),
            '.bp4': (0x6698C, 0x66A6C), '.fmt': (0x66178, 0x6626C), '.fmt2': (0x667A8, 0x6689C),
            '.hdr2': (0x201C0, 0x20200), '.cbp': (0x66A78, 0x66B38)}
# Frequency/Q display: HP keeps 0x66178 (now the new routine's HP entry); BP2/BP4/Contrary BP -> bp_fmt
FMT_SLOTS = {0x689D8 + 0x1C: 0x667A8, 0x68A04 + 0x1C: 0x667A8, 0x68A30 + 0x1C: 0x667A8,
             0x688FC + 0x1C: 0x66178, 0x68928 + 0x1C: 0x66178}
# vtable -> (stock cf, stock pq, new cf, new pq)
VTABLES = {0x688FC: (0x660CC, 0x66140, 'hp2_cf', 'hp2_pq'), 0x68928: (0x66278, 0x662F0, 'hp4_cf', 'hp4_pq'),
           0x689D8: (0x668A8, 0x66934, 'bp2_cf', 'bp2_pq'), 0x68A04: (0x6698C, 0x66A1C, 'bp4_cf', 'bp4_pq'),
           0x68A30: (0x66A78, 0x66AF8, 'cbp_cf', 'cbp_pq')}
STOCK = '/Users/tony/OpenWork Chat/EOS/eos47/bin/eos470_flash_0x20000.bin'   # every replaced body must equal stock 4.70


def run(*cmd):
    subprocess.run(cmd, check=True, cwd=PDIR)


def tables_inc():
    lines = ['| generated by tools/hpbp.py']
    for kind in ('HP', 'BP'):
        svf, lada, ladb = hpbp.tables(kind)
        for name, t in (('SVF', svf), ('LADA', lada), ('LADB', ladb)):
            lines.append(f'        .macro {kind}_{name}_TABLE')
            for i in range(0, len(t), 4):
                lines.append('        .long   ' + ', '.join(f'0x{w:08X}' for w in t[i:i + 4]))
            lines.append('        .endm')
    t = hpbp.cbp_table()
    lines.append('        .macro CBP_TABLE')
    for i in range(0, len(t), 4):
        lines.append('        .long   ' + ', '.join(f'0x{w:08X}' for w in t[i:i + 4]))
    lines.append('        .endm')
    lines.append(f'        .equ    BP4_BOOST, {hpbp.BP4_BOOST}')
    open(os.path.join(PDIR, 'tables.inc'), 'w').write('\n'.join(lines) + '\n')


def assemble():
    tables_inc()
    run(BIN + 'm68k-elf-as', '-mcpu=5206e', '-o', 'hpbp.o', 'hpbp.s')
    ld = 'SECTIONS {\n' + ''.join(f'  {s} 0x{lo:X} : {{ hpbp.o({s}) }}\n' for s, (lo, _) in SECTIONS.items()) + '}\n'
    open(os.path.join(PDIR, 'hpbp.ld'), 'w').write(ld)
    run(BIN + 'm68k-elf-ld', '-T', 'hpbp.ld', '-e', '_start', '-o', 'hpbp.elf', 'hpbp.o')
    data = {}
    for s in SECTIONS:
        out = f'hpbp{s.replace(".", "_")}.bin'
        run(BIN + 'm68k-elf-objcopy', '-O', 'binary', '-j', s, 'hpbp.elf', out)
        data[s] = open(os.path.join(PDIR, out), 'rb').read()
    syms = {}
    for line in subprocess.run([BIN + 'm68k-elf-nm', 'hpbp.elf'], check=True, capture_output=True, text=True,
                               cwd=PDIR).stdout.splitlines():
        a, _, n = line.split()
        syms[n] = int(a, 16)
    return data, syms


def build(base_path, out_path, name=NAME):
    img = bytearray(open(base_path, 'rb').read())
    size0 = len(img)
    data, syms = assemble()
    for s, (lo, hi) in SECTIONS.items():
        if len(data[s]) > hi - lo:
            raise SystemExit(f'{s}: {len(data[s])} bytes > {hi - lo}')
    for vt, (cf, pq, _, _) in VTABLES.items():
        cur = struct.unpack('>II', img[vt + 0x14 - BASE:vt + 0x1C - BASE])
        if cur != (cf, pq):
            raise SystemExit(f'vtable {vt:#x}: slots {cur[0]:#x}/{cur[1]:#x}, expected stock {cf:#x}/{pq:#x}')
    stock = open(STOCK, 'rb').read()
    for s_, (lo, hi) in SECTIONS.items():
        if s_ in ('.hdr2',):
            continue
        if img[lo - BASE:hi - BASE] != stock[lo - BASE:hi - BASE]:
            raise SystemExit(f'{s_} {lo:#x}-{hi - 1:#x} differs from stock 4.70')
    for a, stock in FMT_SLOTS.items():
        if struct.unpack('>I', img[a - BASE:a - BASE + 4])[0] != stock:
            raise SystemExit(f'formatter slot {a:#x} not stock')
    for s in ('.hdr2',):
        lo, hi = SECTIONS[s]
        if bytes(img[lo - BASE:hi - BASE]) != bytes(hi - lo):
            raise SystemExit(f'{s} area {lo:#x}-{hi - 1:#x} is not zero (LFO/Transwave header code grew?)')
    for s, (lo, hi) in SECTIONS.items():
        img[lo - BASE:lo - BASE + len(data[s])] = data[s]
        if s != '.hdr2':
            img[lo - BASE + len(data[s]):hi - BASE] = b'\x4e\x71' * ((hi - lo - len(data[s])) // 2)
    for vt, (_, _, ncf, npq) in VTABLES.items():
        struct.pack_into('>II', img, vt + 0x14 - BASE, syms[ncf], syms[npq])
    if syms['hp_fmt'] != 0x66178:
        raise SystemExit('hp_fmt must stay at 0x66178')
    for a, stock in FMT_SLOTS.items():
        if stock == 0x667A8:
            struct.pack_into('>I', img, a - BASE, syms['bp_fmt'])
    if len(name) > 24:
        raise SystemExit(f'header name {name!r} is {len(name)} bytes; the field holds 24')
    img[0x18:0x30] = name.ljust(24, b' ')
    if len(img) != size0:
        raise SystemExit('image size changed while patching')
    struct.pack_into('>II', img, 4, 0, 0xffffffff)
    c = eos_lz.csum(img)
    struct.pack_into('>II', img, 4, c, c ^ 0xffffffff)
    open(out_path, 'wb').write(img)
    print(f'{out_path}: ' + ', '.join(f'{s} {len(data[s])}/{hi - lo}' for s, (lo, hi) in SECTIONS.items())
          + f'; checksum {c:08x}; name {name.decode()!r}')
    return syms


if __name__ == '__main__':
    build(sys.argv[1], sys.argv[2], *(a.encode() for a in sys.argv[3:4]))
