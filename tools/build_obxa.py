#!/usr/bin/env python3
"""Build the OB-Xa lowpass patch (option B + OB-Xa 4-pole + 4+2 cascade 6-pole).

usage: build_obxa.py BASE.bin OUT.bin
Generates patches/obxa/tables.inc from tools/obxa.py, assembles patches/obxa/obxa_lp.s with
m68k-elf-as -mcpu=5206e, links at 0x65E18, and installs it in place of the stock LP2/LP4/LP6 code.
"""
import hashlib, os, struct, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import eos_lz   # noqa: E402
import obxa     # noqa: E402

ROOT = os.path.dirname(HERE)
PDIR = os.path.join(ROOT, 'patches', 'obxa')
BASE = 0x20000
REGION = (0x65E18, 0x660C0)
NAME = b'EOS 4.70 OB-Xa LP v3d'
DRIVE = False   # v3c Drive experiment: gain word cannot saturate, wraps at the top (hardware 2026-10-18)
EXT = (0x68BF0, 0x68CA0)      # dormant, unreferenced filter method tables reused for v3c code
LADB16 = 0x6875C
BIN = '/opt/homebrew/bin/'

# method table slots repointed: vtable -> [(slot offset, stock target, new symbol)]
VTABLES = {
    0x68878: [(0x0C, 0x65E8C, 'lp2_type'), (0x10, 0x65E90, 'lp2_name'), (0x14, 0x65E98, 'lp2_cf'), (0x18, 0x65F1C, 'lp2_pq'),
              (0x1C, 0x65D24, 'lp_fmt'), (0x20, 0x65C90, 'lp_nparams')],
    0x688A4: [(0x0C, 0x65F40, 'lp4_type'), (0x10, 0x65F44, 'lp4_name'), (0x14, 0x65F4C, 'lp4_cf'), (0x18, 0x65FCC, 'lp4_pq'),
              (0x1C, 0x65D24, 'lp_fmt'), (0x20, 0x65C90, 'lp_nparams')],
    0x688D0: [(0x0C, 0x65FF4, 'lp6_type'), (0x10, 0x65FF8, 'lp6_name'), (0x14, 0x66000, 'lp6_cf'), (0x18, 0x6608C, 'lp6_pq'),
              (0x1C, 0x65D24, 'lp_fmt'), (0x20, 0x65C90, 'lp_nparams')],
}


def run(*cmd):
    subprocess.run(cmd, check=True, cwd=PDIR)


def assemble():
    svf, lada, ladb = obxa.tables()
    with open(os.path.join(PDIR, 'tables.inc'), 'w') as f:
        f.write(f'| generated by tools/obxa.py  K4_MAX={obxa.K4_MAX} Q2_MAX={obxa.Q2_MAX} LP6_CAP={obxa.LP6_CAP}\n')
        for name, t in (('SVF', svf), ('LADA', lada)):
            f.write(f'| {name}\n')
            for i in range(0, 32, 4):
                f.write('        .long   ' + ', '.join(f'0x{w:08X}' for w in t[i:i + 4]) + '\n')
    run(BIN + 'm68k-elf-as', '-mcpu=5206e', '--defsym', f'LP6_CAP={obxa.LP6_CAP}', '--defsym', f'DRIVE={int(DRIVE)}',
        '-o', 'obxa_lp.o', 'obxa_lp.s')
    with open(os.path.join(PDIR, 'obxa.ld'), 'w') as f:
        f.write('SECTIONS {\n  .text 0x%X : { obxa_lp.o(.text) }\n  .ext 0x%X : { obxa_lp.o(.ext) }\n}\n' % (REGION[0], EXT[0]))
    run(BIN + 'm68k-elf-ld', '-T', 'obxa.ld', '-e', '_start', '-o', 'obxa_lp.elf', 'obxa_lp.o')
    run(BIN + 'm68k-elf-objcopy', '-O', 'binary', '-j', '.text', 'obxa_lp.elf', 'obxa_lp.bin')
    run(BIN + 'm68k-elf-objcopy', '-O', 'binary', '-j', '.ext', 'obxa_lp.elf', 'obxa_ext.bin')
    syms = {}
    out = subprocess.run([BIN + 'm68k-elf-nm', 'obxa_lp.elf'], check=True, capture_output=True, text=True, cwd=PDIR).stdout
    for line in out.splitlines():
        a, _, n = line.split()
        syms[n] = int(a, 16)
    code = open(os.path.join(PDIR, 'obxa_lp.bin'), 'rb').read()
    ext = open(os.path.join(PDIR, 'obxa_ext.bin'), 'rb').read() if os.path.exists(os.path.join(PDIR, 'obxa_ext.bin')) else b''
    return code, syms, ext


def external_refs(img, region=None):
    """Any long pointer or bsr/jsr into the region from outside it (other than the vtable slots)."""
    lo, hi = region or REGION
    allowed = {vt + off for vt, slots in VTABLES.items() for off, _, _ in slots}
    hits = []
    for o in range(0, len(img) - 4, 2):
        a = BASE + o
        if lo <= a < hi:
            continue
        v = struct.unpack('>I', img[o:o + 4])[0]
        if lo <= v < hi and a not in allowed and (img[o - 2:o] in (b'\x4e\xb9', b'\x4e\xf9', b'\x20\x3c', b'\x41\xf9', b'\x43\xf9', b'\x48\x79', b'\x2a\xbc', b'\x20\xbc') or region):
            hits.append((a - 2, v))
        if img[o:o + 2] in (b'\x61\x00', b'\x60\x00'):
            t = a + 2 + struct.unpack('>h', img[o + 2:o + 4])[0]
            if lo <= t < hi:
                hits.append((a, t))
    return hits


def build(base_path, out_path):
    img = bytearray(open(base_path, 'rb').read())
    lo, hi = REGION
    region = bytes(img[lo - BASE:hi - BASE])
    sha = hashlib.sha1(region).hexdigest()
    code, syms, ext = assemble()
    if len(code) > hi - lo:
        raise SystemExit(f'patch too big: {len(code)} > {hi - lo}')
    if len(ext) > EXT[1] - EXT[0]:
        raise SystemExit(f'ext too big: {len(ext)} > {EXT[1] - EXT[0]}')
    # the dormant tables must be the stock bytes and unreferenced (checked by external_refs on EXT too)
    eo = EXT[0] - BASE
    if img[eo:eo + 8] != bytes(8) or struct.unpack('>I', img[eo + 8:eo + 12])[0] != 0x1AB1B4:
        raise SystemExit('EXT region is not the stock dormant method tables')
    for vt, slots in VTABLES.items():
        for off, stock, _ in slots:
            cur = struct.unpack('>I', img[vt + off - BASE:vt + off - BASE + 4])[0]
            if cur != stock:
                raise SystemExit(f'vtable {vt:#x}+{off:#x} = {cur:#x}, expected {stock:#x}')
    refs = external_refs(img) + external_refs(img, EXT)
    if refs:
        raise SystemExit('outside references into patched regions: ' + ', '.join(f'{a:#x}->{t:#x}' for a, t in refs))
    # stock region must be the known 4.70 bytes (first function = FUN_00065E18 prologue)
    if region[:4] != bytes.fromhex('2f077211'):
        raise SystemExit('region does not start with stock FUN_00065E18')
    img[lo - BASE:hi - BASE] = code + b'\x4e\x71' * ((hi - lo - len(code)) // 2)
    if DRIVE:
        img[EXT[0] - BASE:EXT[1] - BASE] = ext + b'\x4e\x71' * ((EXT[1] - EXT[0] - len(ext)) // 2)
    for vt, slots in VTABLES.items():
        for off, _, sym in slots:
            if not DRIVE and sym in ('lp_fmt', 'lp_nparams'):
                continue
            struct.pack_into('>I', img, vt + off - BASE, syms[sym])
    # LADB16 goes into the old RES16 slot (only referenced by the code being replaced)
    o = LADB16 - BASE
    stock_res16 = b''.join(struct.pack('>I', w) for w in obxa.ef.RES16)
    if bytes(img[o:o + 64]) != stock_res16:
        raise SystemExit('RES16 slot does not hold the stock table')
    img[o:o + 64] = b''.join(struct.pack('>I', w) for w in obxa.ladb16(obxa.tables()[2]))
    assert img[0x18:0x30].startswith(b'EOS v4.70')
    img[0x18:0x30] = NAME.ljust(24, b' ')
    struct.pack_into('>II', img, 4, 0, 0xffffffff)
    c = eos_lz.csum(img)
    struct.pack_into('>II', img, 4, c, c ^ 0xffffffff)
    open(out_path, 'wb').write(img)
    print(f'{out_path}: code+tables {len(code)} / {hi - lo} bytes, ext {len(ext)} / {EXT[1] - EXT[0]}, stock region sha1 {sha[:12]}, checksum {c:08x}')
    print('symbols: ' + ', '.join(f'{k}={v:#x}' for k, v in sorted(syms.items(), key=lambda kv: kv[1])
                                    if not k.startswith(('_', '.')) and k != 'end_of_patch'))
    return syms


if __name__ == '__main__':
    build(sys.argv[1], sys.argv[2])
